using System;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Threading.Tasks;
using AntColony.Core;
using AntColony.Data;
using AntColony.Buildings;
using AntColony.Units;
using AntColony.World;
using AntColony.Save;
using UnityEngine;

public static class Sustain1114Checks
{
    const BindingFlags Hidden = BindingFlags.Instance | BindingFlags.NonPublic;
    static object Call(CommanderAnt c, string name, params object[] args) => typeof(CommanderAnt).GetMethod(name, Hidden).Invoke(c,args);
    public static async Task<string> Run()
    {
        if (!Application.isPlaying || Time.timeScale != 0 || !(SaveStorage.RootOverride ?? "").Contains("Sustain1114")) throw new Exception("Paused isolated fixture required");
        int count = 0; void Check(bool ok, string reason) { if (!ok) throw new Exception(reason); count++; }
        var c = CommanderRoster.Instance.Commanders.First(); var rm = ResourceManager.Instance;
        foreach(var type in CookedFoods.MealTypes.Concat(new[]{ResourceType.Water, ResourceType.PlantingMaterial})) rm.TrySpend(type,rm.GetAmount(type));
        var template = SupplyBuildingTemplates.Create(BuildingKind.StarterMushroomBed);
        var go = UnityEngine.Object.Instantiate(template, c.Position + Vector3.right * 10, Quaternion.identity);
        go.name = "FIXTURE crop"; go.SetActive(true); await Task.Delay(100);
        var crop = go.GetComponent<StarterCropBed>();
        Check(!crop.Plant(), "No seeds cannot plant");
        rm.Add(ResourceType.PlantingMaterial,1);
        Check(crop.Plant() && rm.GetAmount(ResourceType.PlantingMaterial)==0, "Plant consumes one seed");
        Check(!crop.Plant(), "Cannot double-plant");
        crop.Tick(StartSupplyRules.CropSeconds);
        Check(crop.Crop.growth==0, "No water cannot grow");
        rm.Add(ResourceType.Water,6);
        int before = ProductionStock.Count(ResourceType.Food);
        crop.Tick(StartSupplyRules.CropSeconds);
        Check(ProductionStock.Count(ResourceType.Food)-before==12, "Three-day harvest provides twelve food");
        Check(rm.GetAmount(ResourceType.Water)==3, "One cycle consumes three water");
        Check(crop.Crop.planted && crop.Crop.growth==0, "Harvest retains planting for regrowth");
        crop.Tick(StartSupplyRules.CropSeconds);
        Check(ProductionStock.Count(ResourceType.Food)-before==24, "Second cycle regrows without another seed");
        Check(rm.GetAmount(ResourceType.Water)==0, "Second cycle pays its own water");
        crop.Tick(StartSupplyRules.CropSeconds);
        Check(ProductionStock.Count(ResourceType.Food)-before==24, "Water exhaustion stops further harvests");
        var saved = JsonUtility.FromJson<StarterCropBed.State>(JsonUtility.ToJson(new StarterCropBed.State{planted=true,growth=225,wateredSeconds=75}));
        Check(StarterCropBed.Valid(saved), "Existing mid-cycle state remains valid");
        crop.RestoreCrop(saved); crop.Tick(75);
        Check(crop.Crop.growth==300 && crop.Crop.wateredSeconds==0, "Restored crop consumes remaining water exactly");
        crop.RestoreCrop(new StarterCropBed.State{planted=true,growth=449.9999f,wateredSeconds=0});
        int stalledFood=ProductionStock.Count(ResourceType.Food);
        crop.Tick(.02f);
        Check(ProductionStock.Count(ResourceType.Food)==stalledFood+12 && crop.Crop.growth==0, "Rounded completed crop harvests without demanding a fourth water");
        rm.Add(ResourceType.Water,3);
        for (int i=0;i<27001;i++) crop.Tick(1f/60f);
        Check(ProductionStock.Count(ResourceType.Food)==stalledFood+24, "Frame-sized updates finish a full cycle on exactly three water");
        Check(rm.GetAmount(ResourceType.Water)==0, "Frame-sized cycle does not grant water");

        GameSession.Instance.MarkStarted(10,30); c.CommandStop();
        c.PersonalState.health = new HealthState {migrated=true}; c.WorkState.health=100;
        c.Traits.values.Remove(CommanderTrait.Ascetic);
        c.PersonalState.meal = new CommanderMealState {satiety=20, retrySeconds=2};
        c.PersonalState.joy = new CommanderJoyState {playSeconds=20,freeWalk=true};
        Call(c,"TickMeal",3f);
        Check(c.PersonalState.meal.retrySeconds==0, "Meal retry clock advances during recreation");
        c.PersonalState.joy.playSeconds=0;
        typeof(WorkerAnt).GetMethod("RestoreCargo",Hidden).Invoke(c,new object[]{5f,ResourceType.Wood,null});
        c.PersonalState.meal.retrySeconds=2;
        Call(c,"TickMeal",3f);
        Check(c.PersonalState.meal.retrySeconds==0 && c.CarriedAmount==5, "Meal retry clock advances while preserving cargo");
        typeof(WorkerAnt).GetMethod("DropCargo",Hidden).Invoke(c,null);
        c.PersonalState.meal = new CommanderMealState{satiety=20,diet=CommanderAnt.DietSimple};
        c.PersonalState.moodFactors.Clear();
        Call(c,"FetchMeal",false);
        Check(c.PersonalState.moodFactors.Single(f=>f.reason=="Hunger").value == -5, "Waiting with remaining satiety is not severe starvation");
        Check(!c.PersonalState.moodFactors.Any(f=>f.reason=="굶주림 누적"), "Ordinary meal wait does not add starvation history");
        c.PersonalState.meal.satiety=0;
        Call(c,"FetchMeal",false);
        Check(c.PersonalState.moodFactors.Single(f=>f.reason=="Hunger").value == -15, "Empty satiety retains severe starvation penalty");
        Check(c.PersonalState.moodFactors.Any(f=>f.reason=="굶주림 누적"), "Actual starvation still records cumulative mood");
        c.PersonalState.AddMood("fixture other concern",-3,60);
        c.PersonalState.meal.quality=0;
        Call(c,"FinishMeal");
        Check(c.Satiety==100 && !c.PersonalState.moodFactors.Any(f=>f.reason=="Hunger"), "Completed meal clears immediate hunger");
        Check(c.PersonalState.moodFactors.Any(f=>f.reason=="fixture other concern"), "Meal does not erase unrelated concerns");
        c.CommandStop();
        c.PersonalState.meal = new CommanderMealState {satiety=10, retrySeconds=25, diet=CommanderAnt.DietRaw};
        Call(c,"TickMeal",.1f);
        Check(c.PersonalState.meal.retrySeconds > 24, "Missing food retains retry backoff");
        rm.Add(ResourceType.Food,c.RationPortion);
        c.PersonalState.meal.diet=CommanderAnt.DietSimple;
        Call(c,"TickMeal",.1f);
        Check(c.PersonalState.meal.retrySeconds > 24, "Forbidden raw food does not bypass retry");
        c.PersonalState.meal.diet=CommanderAnt.DietRaw;
        Check((bool)typeof(CommanderAnt).GetMethod("HasFoodFor",BindingFlags.Static|BindingFlags.NonPublic).Invoke(null,new object[]{c}), "Fixture food is reachable and allowed");
        Call(c,"TickMeal",.1f);
        Check(c.PersonalState.meal.retrySeconds == 0, "Newly stocked food ends the retry wait immediately");
        c.CommandStop();
        c.PersonalState.meal = new CommanderMealState {satiety=10, retrySeconds=25, diet=CommanderAnt.DietRaw};
        c.PersonalState.sleep = new CommanderSleepState();
        c.PersonalState.hygiene = new CommanderHygieneState();
        c.PersonalState.joy = new CommanderJoyState();
        c.PersonalState.carriedRations = new FoodLots();
        rm.Add(ResourceType.Food,c.RationPortion);
        typeof(WorkerAnt).GetMethod("RestoreCargo",Hidden).Invoke(c,new object[]{5f,ResourceType.Wood,null});
        c.TickDuty(.1f);
        Check(c.CarriedAmount==0 && c.PersonalState.meal.retrySeconds==0, "Available food interrupts cargo even during retry backoff");
        c.CommandStop();
        c.PersonalState.meal = new CommanderMealState {satiety=20,diet=CommanderAnt.DietRaw};
        c.PersonalState.carriedRations = new FoodLots();
        c.PersonalState.carriedRations.Add(c.RationPortion*2,600);
        Call(c,"TickCarriedMeal",.1f);
        Check(c.PersonalState.meal.served && !c.IsEating, "Carried meal enters normal table approach before eating");
        Check(c.CarriedRationMeals==1, "Preparing carried meal consumes exactly one portion");
        c.PersonalState.meal=JsonUtility.FromJson<CommanderMealState>(JsonUtility.ToJson(c.PersonalState.meal));
        Call(c,"TickCarriedMeal",.1f);
        Check(c.CarriedRationMeals==1 && c.PersonalState.meal.served, "Restored prepared meal never takes another carried portion");
        foreach (var n in ResourceNode.Available.Where(n => n.IsLooseCargo && n.ResourceType == ResourceType.Water).ToArray()) n.gameObject.SetActive(false);
        rm.TrySpend(ResourceType.Water,rm.GetAmount(ResourceType.Water));
        var source = SupplyFacility.All.First(s => s.Kind == BuildingKind.WaterSource);
        var wellObject = UnityEngine.Object.Instantiate(SupplyBuildingTemplates.Create(BuildingKind.ManualWell), source.Position + Vector3.right * 2, Quaternion.identity);
        wellObject.SetActive(true); await Task.Delay(50);
        var well = wellObject.GetComponent<SupplyFacility>();
        well.RestoreSupply(new SupplyFacility.State{fluid=(int)ResourceType.Water,amount=100});
        Check(StarterCropBed.NeedsWaterSupply && CommanderAnt.ManualWellNeedsWork(well), "Full well still offers work when disconnected crops need water");
        var waterBefore = ProductionStock.Count(ResourceType.Water);
        well.WorkManual(.1f);
        Check(well.Supply.amount==90 && ProductionStock.Count(ResourceType.Water)==waterBefore+10, "Well releases existing water without creating free water");
        var water = ResourceNode.Available.First(n => n.IsLooseCargo && n.ResourceType==ResourceType.Water);
        int priority=(int)typeof(CommanderAnt).GetMethod("WorkNeedPriority",BindingFlags.Static|BindingFlags.NonPublic).Invoke(null,new object[]{water,CommanderJobs.Hauling,false,false,false});
        Check(priority==3, "Water delivery receives crop-supply priority");
        rm.Add(ResourceType.Water,StarterCropBed.WaterReserveTarget);
        Check(!StarterCropBed.NeedsWaterSupply, "Stock and pending water cap automatic exports");
        well.RestoreSupply(new SupplyFacility.State{fluid=(int)ResourceType.Water,amount=100});
        Check(!CommanderAnt.ManualWellNeedsWork(well), "Full well idles once crop reserve exists");
        var result="PASS "+count+" crop supply and living-needs assertions; disposable injected fixture, not natural play.";
        File.WriteAllText("work/sustain-1114/regression.txt",result);return result;
    }
}
